/**
 * @file Generates a complete file catalog from source headers and curated non-code descriptions.
 * Functions: collectFiles, describeFile, extractHeaderDescription, renderCatalog, main.
 * Variables: ROOT, OUTPUT, EXCLUDED_DIRECTORIES, STATIC_DESCRIPTIONS, checkOnly.
 * Line locations: see docs/CODE_INDEX.md for the generated symbol index.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "docs", "FILE_CATALOG.md");
const EXCLUDED_DIRECTORIES = new Set([
  ".git",
  ".runtime",
  ".lighthouseci",
  "coverage",
  "dist",
  "node_modules",
  "playwright-report",
  "test-results",
]);
const checkOnly = process.argv.includes("--check");
const STATIC_DESCRIPTIONS = new Map([
  [".editorconfig", "Editor-neutral whitespace and newline policy."],
  [".gitattributes", "Cross-platform Git text and line-ending policy."],
  [".gitignore", "Generated dependency, build, browser-test, and runtime exclusions."],
  [".prettierignore", "Files intentionally excluded from automated formatting."],
  [".prettierrc.json", "Repository formatting policy."],
  ["LICENSE", "MIT license terms."],
  ["package.json", "Pinned toolchain, metadata, and reproducible scripts."],
  ["package-lock.json", "Exact npm dependency graph for deterministic installation."],
  ["jsconfig.json", "Strict JavaScript type-checking configuration."],
  ["public/manifest.webmanifest", "Install metadata, colors, scope, and icon declarations."],
  [
    "public/fixtures/sample-incidents.json",
    "Synthetic, non-sensitive demonstration incident records.",
  ],
  ["public/icons/timeline.svg", "Scalable install and favicon artwork."],
]);

/**
 * Recursively collects authored files in deterministic order.
 * @param {string} directory Current directory.
 * @returns {Promise<string[]>} Relative file paths.
 */
async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const results = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    if (EXCLUDED_DIRECTORIES.has(entry.name)) {
      continue;
    }
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      results.push(...(await collectFiles(absolute)));
    } else {
      results.push(path.relative(ROOT, absolute).replaceAll("\\", "/"));
    }
  }
  return results;
}

/**
 * Extracts an @file, HTML File:, shell File:, or first prose description.
 * @param {string} source File text.
 * @returns {string | null} Header description.
 */
function extractHeaderDescription(source) {
  const fileTag = source.match(/@file\s+([^\r\n*]+)/u)?.[1]?.trim();
  if (fileTag) {
    return fileTag;
  }
  const fileLine = source.match(/(?:File:|# File:)\s*([^\r\n]+)/u)?.[1]?.trim();
  if (fileLine) {
    const withoutCommentEnd = fileLine.endsWith("--!>")
      ? fileLine.slice(0, -4)
      : fileLine.endsWith("-->")
        ? fileLine.slice(0, -3)
        : fileLine;
    return withoutCommentEnd.trim();
  }
  return null;
}

/**
 * Provides a concise purpose for any authored file.
 * @param {string} file Relative file path.
 * @param {string} source File text.
 * @returns {string} Catalog description.
 */
function describeFile(file, source) {
  const staticDescription = STATIC_DESCRIPTIONS.get(file);
  if (staticDescription) {
    return staticDescription;
  }
  const headerDescription = extractHeaderDescription(source);
  if (headerDescription) {
    return headerDescription;
  }
  if (file === "README.md")
    return "Project overview, quick start, feature guide, evidence, and repository map.";
  if (file === "SECURITY.md")
    return "Security model, supported versions, reporting, and safe-data policy.";
  if (file === "CONTRIBUTING.md") return "Contributor workflow and quality gates.";
  if (file.endsWith(".md"))
    return "Project documentation described by its title and section contents.";
  if (file.endsWith(".yml") || file.endsWith(".yaml")) return "Automation configuration.";
  return "Repository support file.";
}

/**
 * Renders the complete deterministic file catalog.
 * @param {{file: string, description: string}[]} records File descriptions.
 * @returns {string} Markdown document.
 */
function renderCatalog(records) {
  const lines = [
    "# File catalog",
    "",
    "> Generated by `npm run file-catalog`. Generated build, dependency, coverage, and browser-report directories are excluded.",
    "",
    "| File | Purpose |",
    "|---|---|",
  ];
  for (const record of records) {
    lines.push(`| \`${record.file}\` | ${record.description.replaceAll("|", "\\|")} |`);
  }
  return `${lines.join("\n")}\n`;
}

/** Generates or verifies the repository-wide file catalog. */
async function main() {
  const files = await collectFiles(ROOT);
  const records = [];
  for (const file of files) {
    const source = await readFile(path.join(ROOT, file), "utf8");
    records.push({ file, description: describeFile(file, source) });
  }
  const rendered = await format(renderCatalog(records), { parser: "markdown" });
  if (checkOnly) {
    const existing = await readFile(OUTPUT, "utf8");
    if (existing !== rendered) {
      throw new Error("docs/FILE_CATALOG.md is stale; run npm run file-catalog.");
    }
    console.log(`File catalog is current for ${records.length} files.`);
    return;
  }
  await writeFile(OUTPUT, rendered, "utf8");
  console.log(`Cataloged ${records.length} files in ${path.relative(ROOT, OUTPUT)}.`);
}

await main();
