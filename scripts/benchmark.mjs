/**
 * @file Benchmarks normalization, stable ordering, indexed filtering, serialization size, and memory delta.
 * Functions: syntheticRecords, percentile, measure, renderReport, main.
 * Variables: ROOT, OUTPUT_JSON, OUTPUT_MARKDOWN, EVENT_COUNT, THRESHOLDS, checkOnly.
 * Line locations: see docs/CODE_INDEX.md for the generated symbol index.
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { EventIndex } from "../src/core/event-index.js";
import { normalizeRecords } from "../src/core/event.js";

/**
 * @typedef {object} BenchmarkMetrics
 * @property {number} normalizeAndSortMs
 * @property {number} buildIndexMs
 * @property {number} queryP50Ms
 * @property {number} queryP95Ms
 * @property {number} queryP99Ms
 * @property {number} heapDeltaMiB
 */
/**
 * @typedef {object} BenchmarkReport
 * @property {string} generatedAt
 * @property {string} runtime
 * @property {string} platform
 * @property {BenchmarkMetrics} metrics
 */

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_JSON = path.join(ROOT, "docs", "reports", "generated", "benchmark.json");
const OUTPUT_MARKDOWN = path.join(ROOT, "docs", "reports", "PERFORMANCE.md");
const EVENT_COUNT = 50_000;
const checkOnly = process.argv.includes("--check");
const THRESHOLDS = {
  normalizeAndSortMs: 4_000,
  buildIndexMs: 2_000,
  queryP95Ms: 25,
  heapDeltaMiB: 160,
};

/**
 * Generates deterministic synthetic events with ties and reusable filter cardinalities.
 * @param {number} count Number of records.
 * @returns {Record<string, unknown>[]} Raw records.
 */
function syntheticRecords(count) {
  const severities = ["info", "warning", "error", "critical"];
  const services = ["gateway", "identity", "scheduler", "database", "telemetry"];
  const base = Date.parse("2026-01-01T00:00:00.000Z");
  return Array.from({ length: count }, (_, index) => ({
    id: `bench-${index}`,
    timestamp: new Date(base + Math.floor(index / 3) * 17).toISOString(),
    severity: severities[index % severities.length],
    service: services[index % services.length],
    message: `Synthetic ${index % 19 === 0 ? "timeout" : "state transition"} event ${index}`,
    correlationId: `chain-${index % 200}`,
    metadata: { partition: index % 8 },
  }));
}

/**
 * Measures one synchronous operation with high-resolution timing.
 * @template T
 * @param {() => T} operation Work to measure.
 * @returns {{value: T, durationMs: number}} Result and duration.
 */
function measure(operation) {
  const startedAt = performance.now();
  const value = operation();
  return { value, durationMs: performance.now() - startedAt };
}

/**
 * Returns a nearest-rank percentile from sorted samples.
 * @param {number[]} samples Samples.
 * @param {number} quantile Quantile from zero to one.
 * @returns {number} Percentile value.
 */
function percentile(samples, quantile) {
  const sorted = [...samples].sort((left, right) => left - right);
  const index = Math.min(sorted.length - 1, Math.max(0, Math.ceil(quantile * sorted.length) - 1));
  return sorted[index] ?? 0;
}

/**
 * Renders a human-readable report with environment and threshold context.
 * @param {BenchmarkReport} report Benchmark evidence.
 * @returns {string} Markdown report.
 */
function renderReport(report) {
  const metrics = report.metrics;
  return `# Performance report

Generated by \`npm run benchmark\` on ${report.generatedAt} using ${report.runtime} on ${report.platform}.

## Workload

- ${EVENT_COUNT.toLocaleString()} deterministic synthetic events.
- Timestamp ties every three records exercise stable ordering.
- 200 correlation groups, five services, four severities, and indexed token queries.
- Timings are engineering evidence from one machine, not universal production guarantees.

## Results

| Metric | Result | Budget | Status |
|---|---:|---:|---|
| Normalize and stable-sort | ${metrics.normalizeAndSortMs.toFixed(3)} ms | ≤ ${THRESHOLDS.normalizeAndSortMs} ms | ${metrics.normalizeAndSortMs <= THRESHOLDS.normalizeAndSortMs ? "Pass" : "Fail"} |
| Build inverted indexes | ${metrics.buildIndexMs.toFixed(3)} ms | ≤ ${THRESHOLDS.buildIndexMs} ms | ${metrics.buildIndexMs <= THRESHOLDS.buildIndexMs ? "Pass" : "Fail"} |
| Indexed query p50 | ${metrics.queryP50Ms.toFixed(3)} ms | informational | — |
| Indexed query p95 | ${metrics.queryP95Ms.toFixed(3)} ms | ≤ ${THRESHOLDS.queryP95Ms} ms | ${metrics.queryP95Ms <= THRESHOLDS.queryP95Ms ? "Pass" : "Fail"} |
| Indexed query p99 | ${metrics.queryP99Ms.toFixed(3)} ms | informational | — |
| Approximate heap delta | ${metrics.heapDeltaMiB.toFixed(3)} MiB | ≤ ${THRESHOLDS.heapDeltaMiB} MiB | ${metrics.heapDeltaMiB <= THRESHOLDS.heapDeltaMiB ? "Pass" : "Fail"} |

The virtual list separately bounds live DOM rows to the viewport plus overscan. Browser performance and Lighthouse budgets run in CI.
`;
}

/** Runs the benchmark, enforces generous cross-run budgets, and optionally records local evidence. */
async function main() {
  const beforeHeap = process.memoryUsage().heapUsed;
  const records = syntheticRecords(EVENT_COUNT);
  const normalized = measure(() => normalizeRecords(records));
  if (normalized.value.issues.length > 0) {
    throw new Error("Synthetic benchmark fixture produced validation issues.");
  }
  const indexed = measure(() => new EventIndex(normalized.value.events));
  const queryDurations = [];
  for (let iteration = 0; iteration < 120; iteration += 1) {
    const query = measure(() =>
      indexed.value.filter({
        query: iteration % 2 === 0 ? "timeout" : "transition",
        severity: iteration % 3 === 0 ? "error" : "",
        service: iteration % 5 === 0 ? "identity" : "",
        correlationId: iteration % 7 === 0 ? `chain-${iteration % 200}` : "",
      }),
    );
    queryDurations.push(query.durationMs);
  }
  const afterHeap = process.memoryUsage().heapUsed;
  /** @type {BenchmarkMetrics} */
  const metrics = {
    normalizeAndSortMs: normalized.durationMs,
    buildIndexMs: indexed.durationMs,
    queryP50Ms: percentile(queryDurations, 0.5),
    queryP95Ms: percentile(queryDurations, 0.95),
    queryP99Ms: percentile(queryDurations, 0.99),
    heapDeltaMiB: Math.max(0, afterHeap - beforeHeap) / 1024 / 1024,
  };
  const report = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    runtime: process.version,
    platform: `${process.platform}-${process.arch}`,
    eventCount: EVENT_COUNT,
    metrics,
    thresholds: THRESHOLDS,
  };
  const failed = Object.entries(THRESHOLDS).filter(([name, threshold]) => {
    const metricName = /** @type {keyof BenchmarkMetrics} */ (name);
    return metrics[metricName] > threshold;
  });
  console.log(JSON.stringify(report, null, 2));
  if (failed.length > 0) {
    throw new Error(`Performance budget exceeded: ${failed.map(([name]) => name).join(", ")}.`);
  }
  if (!checkOnly) {
    await mkdir(path.dirname(OUTPUT_JSON), { recursive: true });
    await writeFile(OUTPUT_JSON, `${JSON.stringify(report, null, 2)}\n`, "utf8");
    await writeFile(OUTPUT_MARKDOWN, renderReport(report), "utf8");
  }
}

await main();
