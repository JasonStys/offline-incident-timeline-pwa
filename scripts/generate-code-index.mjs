/**
 * @file Generates an exact line-number index for functions, classes, variables, and HTML element IDs.
 * Functions: collectFiles, symbolsForFile, htmlIdsForFile, renderIndex, main.
 * Variables: ROOT, OUTPUT, CODE_EXTENSIONS, checkOnly.
 * Line locations: this script indexes itself in docs/CODE_INDEX.md.
 */
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "docs", "CODE_INDEX.md");
const CODE_EXTENSIONS = new Set([".js", ".mjs"]);
const checkOnly = process.argv.includes("--check");

/**
 * Recursively collects authored code and HTML files in deterministic order.
 * @param {string} directory Current directory.
 * @returns {Promise<string[]>} Relative file paths.
 */
async function collectFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const results = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    if (
      [
        ".git",
        ".runtime",
        "coverage",
        "dist",
        "node_modules",
        "playwright-report",
        "test-results",
      ].includes(entry.name)
    ) {
      continue;
    }
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      results.push(...(await collectFiles(absolute)));
    } else if (CODE_EXTENSIONS.has(path.extname(entry.name)) || entry.name.endsWith(".html")) {
      results.push(path.relative(ROOT, absolute).replaceAll("\\", "/"));
    }
  }
  return results;
}

/**
 * Extracts declared functions, classes, and variables using conservative source patterns.
 * @param {string} source Source text.
 * @returns {{line: number, kind: string, name: string}[]} Symbol records.
 */
function symbolsForFile(source) {
  const patterns = [
    { kind: "function", expression: /^(?:export\s+)?(?:async\s+)?function\s+([A-Za-z_$][\w$]*)/ },
    { kind: "class", expression: /^(?:export\s+)?class\s+([A-Za-z_$][\w$]*)/ },
    { kind: "variable", expression: /^(?:export\s+)?(?:const|let|var)\s+([A-Za-z_$][\w$]*)/ },
  ];
  /** @type {{line: number, kind: string, name: string}[]} */
  const symbols = [];
  source.split(/\r?\n/u).forEach((line, index) => {
    const trimmed = line.trim();
    for (const pattern of patterns) {
      const match = pattern.expression.exec(trimmed);
      if (match?.[1]) {
        symbols.push({ line: index + 1, kind: pattern.kind, name: match[1] });
        break;
      }
    }
  });
  return symbols;
}

/**
 * Extracts stable HTML element IDs for UI-to-code navigation.
 * @param {string} source HTML source.
 * @returns {{line: number, kind: string, name: string}[]} Element records.
 */
function htmlIdsForFile(source) {
  /** @type {{line: number, kind: string, name: string}[]} */
  const symbols = [];
  source.split(/\r?\n/u).forEach((line, index) => {
    for (const match of line.matchAll(/\bid="([^"]+)"/gu)) {
      symbols.push({ line: index + 1, kind: "element", name: match[1] ?? "" });
    }
  });
  return symbols;
}

/**
 * Renders deterministic Markdown with exact one-based source positions.
 * @param {{file: string, symbols: {line: number, kind: string, name: string}[]}[]} records Indexed records.
 * @returns {string} Markdown document.
 */
function renderIndex(records) {
  const lines = [
    "# Code index",
    "",
    "> Generated by `npm run code-index`. Line numbers are one-based and are the authority referenced by source-file headers.",
    "",
  ];
  for (const record of records) {
    lines.push(`## \`${record.file}\``, "", "| Line | Kind | Symbol |", "|---:|---|---|");
    if (record.symbols.length === 0) {
      lines.push("| — | file | No declarations indexed |", "");
      continue;
    }
    for (const symbol of record.symbols) {
      lines.push(`| ${symbol.line} | ${symbol.kind} | \`${symbol.name}\` |`);
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** Generates or verifies the exact symbol index. */
async function main() {
  const files = await collectFiles(ROOT);
  const records = [];
  for (const file of files) {
    const source = await readFile(path.join(ROOT, file), "utf8");
    records.push({
      file,
      symbols: file.endsWith(".html") ? htmlIdsForFile(source) : symbolsForFile(source),
    });
  }
  const rendered = renderIndex(records);
  if (checkOnly) {
    const existing = await readFile(OUTPUT, "utf8");
    if (existing !== rendered) {
      throw new Error("docs/CODE_INDEX.md is stale; run npm run code-index.");
    }
    console.log(`Code index is current for ${records.length} files.`);
    return;
  }
  await writeFile(OUTPUT, rendered, "utf8");
  console.log(`Indexed ${records.length} files in ${path.relative(ROOT, OUTPUT)}.`);
}

await main();
